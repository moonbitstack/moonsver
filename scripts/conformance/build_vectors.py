"""Regenerate the conformance corpus and the vectors the tests replay.

The expected results come from two independent, widely used implementations:

    node-semver 7.7.4     versions, precedence, npm ranges, bumps
    semver 1.0.27 (Rust)  versions under the strict spec, precedence, Cargo requirements

The script writes the inputs, runs both references, cross-checks them against each
other, and writes `src/conformance_vectors_test.mbt`. The generated file is committed
so that `moon test` replays it on every target without a network or a file system;
CI runs this script again and fails when the committed copy is stale.

    python scripts/conformance/build_vectors.py

Both references have to be installed: node with npm, and a Rust toolchain.
"""

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import cases  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
RUST = HERE / "rust"
OUTPUT = ROOT / "src" / "conformance_vectors_test.mbt"

NODE_SEMVER = "7.7.4"
RUST_SEMVER = "1.0.27"

HEADER = f"""// Generated by scripts/conformance/build_vectors.py from node-semver {NODE_SEMVER},
// the Rust semver crate {RUST_SEMVER} and the corpus in scripts/conformance/cases.py.
// Run the script to regenerate; do not edit this file by hand.
"""


def run_node(cases_dir, out_dir):
    npm = shutil.which("npm") or "npm"
    with tempfile.TemporaryDirectory() as tmp:
        install = [
            npm,
            "install",
            "--silent",
            "--no-audit",
            "--no-fund",
            "--prefix",
            tmp,
            f"semver@{NODE_SEMVER}",
        ]
        if sys.platform == "win32":
            # npm is a batch file there, and only a shell starts it.
            subprocess.run(subprocess.list2cmdline(install), check=True, shell=True)
        else:
            subprocess.run(install, check=True)
        script = Path(tmp) / "npm_reference.cjs"
        shutil.copy(HERE / "npm_reference.cjs", script)
        subprocess.run(["node", str(script), str(cases_dir), str(out_dir)], check=True)


def run_rust(cases_dir, out_dir):
    manifest = RUST / "Cargo.toml"
    pinned = f'semver = "={RUST_SEMVER}"'
    if pinned not in manifest.read_text(encoding="utf-8"):
        sys.exit(f"{manifest} does not pin {pinned}")
    subprocess.run(
        [
            "cargo",
            "run",
            "--quiet",
            "--manifest-path",
            str(manifest),
            "--",
            str(cases_dir),
            str(out_dir),
        ],
        check=True,
    )


def read_tsv(path):
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        rows.append(line.split("\t"))
    return rows


def agree(npm_rows, rust_rows, what):
    """Both references must order the same pairs the same way."""
    if len(npm_rows) != len(rust_rows):
        sys.exit(f"{what}: the references returned different row counts")
    bad = [
        (a, b)
        for (a, b, npm_sign), (c, d, rust_sign) in zip(npm_rows, rust_rows)
        if (a, b, npm_sign) != (c, d, rust_sign)
    ]
    if bad:
        lines = "\n".join(f"  {a} vs {b}: npm {n}, rust {r}" for (a, b, n, r) in bad[:10])
        sys.exit(f"{what}: the references disagree\n{lines}")
    return len(npm_rows)


def moon_string(text):
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def chunked(items, size):
    return [items[i : i + size] for i in range(0, len(items), size)]


def emit_pairs(name, rows, size=40):
    """Array[(String, Bool)] in chunks, so no single initialiser grows too long."""
    parts = []
    for index, group in enumerate(chunked(rows, size), start=1):
        body = "\n".join(f"    ({moon_string(a)}, {str(b).lower()})," for a, b in group)
        parts.append(f"///|\nfn {name}_{index}() -> Array[(String, Bool)] {{\n  [\n{body}\n  ]\n}}\n")
    joins = [f"{name}_{i}()" for i in range(1, len(parts) + 1)]
    head = f"///|\nfn {name}() -> Array[(String, Bool)] {{\n  let out = {joins[0]}\n"
    for join in joins[1:]:
        head += f"  for row in {join} {{\n    out.push(row)\n  }}\n"
    head += "  out\n}\n"
    return "\n".join(parts) + "\n" + head


def emit_groups(name, groups, size=6):
    """Array[(String, Array[(String, Bool)])], one entry per range string."""
    parts = []
    for index, group in enumerate(chunked(groups, size), start=1):
        body = []
        for text, rows in group:
            inner = "\n".join(f"      ({moon_string(v)}, {str(ok).lower()})," for v, ok in rows)
            body.append(f"    ({moon_string(text)}, [\n{inner}\n    ]),")
        parts.append(
            f"///|\nfn {name}_{index}() -> Array[(String, Array[(String, Bool)])] {{\n  [\n"
            + "\n".join(body)
            + "\n  ]\n}\n"
        )
    joins = [f"{name}_{i}()" for i in range(1, len(parts) + 1)]
    head = (
        f"///|\nfn {name}() -> Array[(String, Array[(String, Bool)])] {{\n"
        f"  let out = {joins[0]}\n"
    )
    for join in joins[1:]:
        head += f"  for row in {join} {{\n    out.push(row)\n  }}\n"
    head += "  out\n}\n"
    return "\n".join(parts) + "\n" + head


def emit_strings(name, values, size=12):
    parts = []
    for index, group in enumerate(chunked(values, size), start=1):
        body = "\n".join(f"    {moon_string(v)}," for v in group)
        parts.append(f"///|\nfn {name}_{index}() -> Array[String] {{\n  [\n{body}\n  ]\n}}\n")
    joins = [f"{name}_{i}()" for i in range(1, len(parts) + 1)]
    head = f"///|\nfn {name}() -> Array[String] {{\n  let out = {joins[0]}\n"
    for join in joins[1:]:
        head += f"  for row in {join} {{\n    out.push(row)\n  }}\n"
    head += "  out\n}\n"
    return "\n".join(parts) + "\n" + head


def emit_precedence(name, rows, size=40):
    """Array[(String, String, Int32)]: every ordered pair and the sign both references give."""
    parts = []
    for index, group in enumerate(chunked(rows, size), start=1):
        body = "\n".join(
            f"    ({moon_string(a)}, {moon_string(b)}, {int(sign)})," for a, b, sign in group
        )
        parts.append(
            f"///|\nfn {name}_{index}() -> Array[(String, String, Int32)] {{\n  [\n{body}\n  ]\n}}\n"
        )
    joins = [f"{name}_{i}()" for i in range(1, len(parts) + 1)]
    head = (
        f"///|\nfn {name}() -> Array[(String, String, Int32)] {{\n  let out = {joins[0]}\n"
    )
    for join in joins[1:]:
        head += f"  for row in {join} {{\n    out.push(row)\n  }}\n"
    head += "  out\n}\n"
    return "\n".join(parts) + "\n" + head


def emit_extremes(name, rows, size=12):
    """Array[(String, String, String, Array[String])]: range, highest, lowest, sorted."""
    parts = []
    for index, group in enumerate(chunked(rows, size), start=1):
        body = []
        for text, high, low, sorted_names in group:
            inner = "\n".join(f"      {moon_string(v)}," for v in sorted_names)
            body.append(
                f"    ({moon_string(text)}, {moon_string(high)}, {moon_string(low)}, [\n{inner}\n    ]),"
            )
        parts.append(
            f"///|\nfn {name}_{index}() -> "
            f"Array[(String, String, String, Array[String])] {{\n  [\n"
            + "\n".join(body)
            + "\n  ]\n}\n"
        )
    joins = [f"{name}_{i}()" for i in range(1, len(parts) + 1)]
    head = (
        f"///|\nfn {name}() -> Array[(String, String, String, Array[String])] {{\n"
        f"  let out = {joins[0]}\n"
    )
    for join in joins[1:]:
        head += f"  for row in {join} {{\n    out.push(row)\n  }}\n"
    head += "  out\n}\n"
    return "\n".join(parts) + "\n" + head


def emit_bumps(name, rows, size=40):
    parts = []
    for index, group in enumerate(chunked(rows, size), start=1):
        body = "\n".join(
            f"    ({moon_string(v)}, {moon_string(r)}, "
            + (f"Some({moon_string(result)})" if result != "-" else "None")
            + "),"
            for v, r, result in group
        )
        parts.append(
            f"///|\nfn {name}_{index}() -> "
            f"Array[(String, String, String?)] {{\n  [\n{body}\n  ]\n}}\n"
        )
    joins = [f"{name}_{i}()" for i in range(1, len(parts) + 1)]
    head = (
        "///|\nfn "
        + name
        + "() -> Array[(String, String, String?)] {\n"
        + f"  let out = {joins[0]}\n"
    )
    for join in joins[1:]:
        head += f"  for row in {join} {{\n    out.push(row)\n  }}\n"
    head += "  out\n}\n"
    return "\n".join(parts) + "\n" + head


def range_groups(rows, texts):
    """Rows of (range index, version index, result) grouped by range text."""
    groups, refused = [], []
    order, seen = [], {}
    for raw_ri, vi, value in rows:
        ri = int(raw_ri)
        if vi == "-1":
            refused.append(texts[ri])
            continue
        if ri not in seen:
            seen[ri] = []
            order.append(ri)
        seen[ri].append((cases.RANGE_VERSIONS[int(vi)], value == "true"))
    for ri in order:
        groups.append((texts[ri], seen[ri]))
    return groups, refused


def main():
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        cases_dir = tmp / "cases"
        npm_out = tmp / "npm"
        rust_out = tmp / "rust"
        cases.write_cases(cases_dir)
        run_node(cases_dir, npm_out)
        run_rust(cases_dir, rust_out)

        def pairs(path):
            return {int(i): v == "true" for i, v in read_tsv(path)}

        npm_versions = [(text, pairs(npm_out / "versions.tsv")[i]) for i, text in enumerate(cases.VERSIONS)]
        rust_versions = [(text, pairs(rust_out / "versions.tsv")[i]) for i, text in enumerate(cases.VERSIONS)]
        npm_precedence = read_tsv(npm_out / "precedence.tsv")
        rust_precedence = read_tsv(rust_out / "precedence.tsv")
        pair_count = agree(npm_precedence, rust_precedence, "precedence")

        npm_rows = read_tsv(npm_out / "ranges_npm.tsv")
        cargo_rows = read_tsv(rust_out / "ranges_cargo.tsv")
        npm_groups, npm_refused = range_groups(npm_rows, cases.RANGES_NPM)
        cargo_groups, cargo_refused = range_groups(cargo_rows, cases.RANGES_CARGO)

        bump_versions = [
            (version, release) for version in cases.BUMP_VERSIONS for release in cases.BUMP_RELEASES
        ]
        bump_rows = read_tsv(npm_out / "bumps.tsv")
        bumps = [
            (bump_versions[int(index)][0], bump_versions[int(index)][1], result)
            for index, result in bump_rows
        ]

        extremes = []
        for ri, high, low, sorted_names in read_tsv(npm_out / "extremes.tsv"):
            order = [cases.RANGE_VERSIONS[int(i)] for i in sorted_names.split(",") if i]
            extremes.append(
                (
                    cases.RANGES_NPM[int(ri)],
                    cases.RANGE_VERSIONS[int(high)] if high != "-1" else "-",
                    cases.RANGE_VERSIONS[int(low)] if low != "-1" else "-",
                    order,
                )
            )

    ordered = [
        (cases.PRECEDENCE[int(a)], cases.PRECEDENCE[int(b)], int(sign))
        for a, b, sign in npm_precedence
    ]
    accepted = sum(len(rows) for _, rows in npm_groups)
    cargo_accepted = sum(len(rows) for _, rows in cargo_groups)
    parts = [
        HEADER,
        emit_pairs("npm_version_cases", npm_versions),
        emit_pairs("strict_version_cases", rust_versions),
        emit_precedence("precedence_cases", ordered),
        emit_strings("npm_refused_ranges", npm_refused),
        emit_groups("npm_range_cases", npm_groups),
        emit_strings("cargo_refused_ranges", cargo_refused),
        emit_groups("cargo_range_cases", cargo_groups),
        emit_strings("range_versions", cases.RANGE_VERSIONS, size=9),
        emit_extremes("npm_extremes", extremes),
        emit_bumps("bump_cases", bumps),
    ]
    OUTPUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    # The formatter decides how the tuples pack, so let it have the last word: the
    # committed copy has to be byte-identical to what this script produces in CI.
    moon = shutil.which("moon")
    if moon:
        subprocess.run([moon, "fmt", str(OUTPUT)], check=True, cwd=ROOT)
    else:
        print("moon is not on PATH: the generated file is not formatted")
    print(
        f"wrote {OUTPUT.relative_to(ROOT)}: {len(npm_versions)} versions, "
        f"{pair_count} ordered pairs, {accepted} npm range checks over {len(npm_groups)} ranges, "
        f"{cargo_accepted} Cargo checks over {len(cargo_groups)} requirements, {len(bumps)} bumps"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
