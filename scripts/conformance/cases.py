# node-semver's `release` returns null for a version with no prerelease, so it is not
# a bump the two can compare; `Release::Stable` is covered in `bump_test.mbt`.
BUMP_RELEASES = [
    "major",
    "minor",
    "patch",
    "premajor",
    "preminor",
    "prepatch",
    "prerelease",
]


def write_cases(directory):
    """Write the corpus as one case per line, in the format the references read."""
    directory.mkdir(parents=True, exist_ok=True)
    files = {
        "versions.txt": VERSIONS,
        "precedence.txt": PRECEDENCE,
        "ranges_npm.txt": RANGES_NPM,
        "ranges_cargo.txt": RANGES_CARGO,
        "range_versions.txt": RANGE_VERSIONS,
        "bumps.txt": [f"{version}\t{release}" for version in BUMP_VERSIONS for release in BUMP_RELEASES],
    }
    for name, lines in files.items():
        (directory / name).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
